/* 
1) En TypeScript las reglas escritas del lenguaje son:
- Sintaxis: reglas para declarar variables, funciones, estructuras de control, tipos, etc.
- Tipos de datos: number, string, boolean, array, object, entre otros.
- Estructuras de control: if, else, switch, for, while, do...while.
- Funciones: permiten organizar el programa en procedimientos reutilizables.
- Asignaciones y expresiones: permiten modificar valores y realizar operaciones.
- Reglas de ambito: determinan dónde puede utilizarse una variable.
- Reglas de tipado: TypeScript incorpora tipado estático, por lo que permite especificar y verificar los tipos de los datos antes de ejecutar el programa.

2) Creencias de los profesionales: En TypeScript se valoran especialmente el tipado estático, la detección temprana de errores, 
la facilidad para mantener y organizar programas de gran tamaño y la integración con JavaScript.
*/
